/// Decimal year of a Julian date (Julian years from J2000.0).
pub fn decimal_year(jd: f64) -> f64 {
    2000.0 + (jd - 2451545.0) / 365.25
}

/// ΔT = TT − UT1 in seconds at the decimal `year` (Stephenson, Morrison & Hohenkerk).
pub fn delta_t_year(year: f64) -> f64 {
    let first = TABLE_S15_2020[0][0];
    let last = TABLE_S15_2020[TABLE_S15_2020.len() - 1][1];
    if !(year >= first && year <= last) {
        let u = (year - 1825.0) / 100.0;
        return -320.0 + 32.5 * u * u;
    }
    let i = TABLE_S15_2020.partition_point(|r| r[1] < year).min(TABLE_S15_2020.len() - 1);
    let [x0, x1, a3, a2, a1, a0] = TABLE_S15_2020[i];
    let t = (year - x0) / (x1 - x0);
    ((a3 * t + a2) * t + a1) * t + a0
}

/// ΔT = TT − UT1 in seconds at the Julian date `jd` (either scale: ΔT changes by well under a
/// millisecond over the difference).
pub fn delta_t(jd: f64) -> f64 {
    delta_t_year(decimal_year(jd))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_published_values() {
        // Table S15.2020 at its knots, and the long-term parabola
        assert!((delta_t_year(1900.0) + 1.977).abs() < 1e-9);
        assert!((delta_t_year(2016.0) - 68.109).abs() < 1e-9);
        assert!((delta_t_year(-1000.0) - (-320.0 + 32.5 * 28.25_f64.powi(2))).abs() < 1e-9);
        // continuous across knots
        for r in TABLE_S15_2020.windows(2) {
            let y = r[0][1];
            assert!((delta_t_year(y - 1e-9) - delta_t_year(y + 1e-9)).abs() < 1.5e-3, "jump at {}", y); // the coefficients are rounded to 1 ms
        }
    }
}
