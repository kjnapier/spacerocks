PX = 128  # font units per pixel
UPM = 8 * PX


def glyph_name(ch):
    return f"uni{ord(ch):04X}" if ch != " " else "space"


def build(path):
    names = [".notdef"] + [glyph_name(c) for c in GLYPHS]
    cmap = {ord(c): glyph_name(c) for c in GLYPHS}
    for c in GLYPHS:
        if c.isalpha() and c.isascii():
            cmap[ord(c.lower())] = glyph_name(c)

    glyphs, metrics = {}, {}
    for name, pattern in [(".notdef", "##### #...# #...# #...# #...# #...# #####")] + [
        (glyph_name(c), p) for c, p in GLYPHS.items()
    ]:
        pen = TTGlyphPen(None)
        for row, bits in enumerate(pattern.split()):
            y = (6 - row) * PX  # bottom row sits on the baseline
            for col, bit in enumerate(bits):
                if bit == "#":
                    x = col * PX
                    pen.moveTo((x, y))
                    pen.lineTo((x, y + PX))
                    pen.lineTo((x + PX, y + PX))
                    pen.lineTo((x + PX, y))
                    pen.closePath()
        glyphs[name] = pen.glyph()
        metrics[name] = (6 * PX, 0)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=7 * PX, descent=-PX)
    fb.setupOS2(sTypoAscender=7 * PX, sTypoDescender=-PX, usWinAscent=7 * PX, usWinDescent=PX)
    fb.setupNameTable({"familyName": "Spacerocks Pixel", "styleName": "Regular"})
    fb.setupPost()
    fb.save(path)


